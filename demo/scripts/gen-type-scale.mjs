#!/usr/bin/env node
/**
 * gen-type-scale.mjs — generates app/type-scale.css from the scale defined
 * below. The fluidClamp math mirrors lib/type-scale.ts exactly (vendored
 * from AleksandrHovhannisyan/fluid-type-scale-calculator, MIT); this script
 * is plain JS so it runs without a TS toolchain. Keep the two in sync.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const MIN_VW = 320;
const MAX_VW = 1280;

function fluidClamp(minPx, maxPx) {
  const slope = (maxPx - minPx) / (MAX_VW - MIN_VW);
  const intercept = minPx - slope * MIN_VW;
  const toRem = (px) => `${(px / 16).toFixed(4).replace(/\.?0+$/, "")}rem`;
  return `clamp(${toRem(minPx)}, ${toRem(intercept)} + ${(slope * 100).toFixed(4)}vw, ${toRem(maxPx)})`;
}

// Ratio 1.25, 5 fluid steps (DESIGN-SYSTEM.md §2). Mirrors lib/type-scale.ts.
const SCALE = [
  { name: "text-body",  minPx: 14, maxPx: 14, lineHeight: 1.6,  letterSpacing: "0",        fontWeight: 400 },
  { name: "text-title", minPx: 16, maxPx: 18, lineHeight: 1.4,  letterSpacing: "-0.01em",  fontWeight: 500 },
  { name: "text-h3",    minPx: 20, maxPx: 23, lineHeight: 1.25, letterSpacing: "-0.015em",fontWeight: 600 },
  { name: "text-h2",    minPx: 26, maxPx: 31, lineHeight: 1.15, letterSpacing: "-0.02em",  fontWeight: 600 },
  { name: "text-h1",    minPx: 34, maxPx: 44, lineHeight: 1.05, letterSpacing: "-0.03em",  fontWeight: 600 },
];

const css =
  "/* GENERATED by scripts/gen-type-scale.mjs — do not hand-edit. Source: lib/type-scale.ts */\n" +
  SCALE.map(
    (s) =>
      `.${s.name} { font-size: ${fluidClamp(s.minPx, s.maxPx)}; line-height: ${s.lineHeight}; letter-spacing: ${s.letterSpacing}; font-weight: ${s.fontWeight}; }`,
  ).join("\n") +
  "\n";

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "app", "type-scale.css");
writeFileSync(out, css);
console.log(`wrote ${out}`);
