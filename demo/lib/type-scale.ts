/**
 * Vendored fluid type-scale generator.
 * Algorithm: linear clamp() interpolation between a min and max viewport,
 * as implemented by AleksandrHovhannisyan/fluid-type-scale-calculator (MIT).
 *
 * slope      = (maxPx - minPx) / (maxVw - minVw)
 * intercept  = minPx - slope * minVw
 * clamp(min, intercept + slope*100vw, max)
 *
 * All sizes resolve to rem so they respect the user's root font size.
 */
export const MIN_VIEWPORT = 320;
export const MAX_VIEWPORT = 1280;

export function fluidClamp(
  minPx: number,
  maxPx: number,
  minVw: number = MIN_VIEWPORT,
  maxVw: number = MAX_VIEWPORT,
): string {
  const slope = (maxPx - minPx) / (maxVw - minVw);
  const intercept = minPx - slope * minVw;
  const toRem = (px: number) => `${(px / 16).toFixed(4).replace(/\.?0+$/, "")}rem`;
  return `clamp(${toRem(minPx)}, ${toRem(intercept)} + ${(slope * 100).toFixed(4)}vw, ${toRem(maxPx)})`;
}

export interface TypeStep {
  /** token name, e.g. "text-h1" */
  name: string;
  minPx: number;
  maxPx: number;
  lineHeight: number;
  letterSpacing: string;
  fontWeight: number;
}

/**
 * The demo's scale. Ratio 1.25, 5 fluid steps (DESIGN-SYSTEM.md §2).
 * caption/eyebrow are fixed 12px labels (all-caps tracking for eyebrow).
 */
export const TYPE_SCALE: TypeStep[] = [
  { name: "text-body",  minPx: 14, maxPx: 14, lineHeight: 1.6,  letterSpacing: "0",       fontWeight: 400 },
  { name: "text-title", minPx: 16, maxPx: 18, lineHeight: 1.4,  letterSpacing: "-0.01em", fontWeight: 500 },
  { name: "text-h3",    minPx: 20, maxPx: 23, lineHeight: 1.25, letterSpacing: "-0.015em",fontWeight: 600 },
  { name: "text-h2",    minPx: 26, maxPx: 31, lineHeight: 1.15, letterSpacing: "-0.02em", fontWeight: 600 },
  { name: "text-h1",    minPx: 34, maxPx: 44, lineHeight: 1.05, letterSpacing: "-0.03em", fontWeight: 600 },
];

export function typeScaleCss(): string {
  const lines = TYPE_SCALE.map((s) => {
    const size = fluidClamp(s.minPx, s.maxPx);
    return `.${s.name} { font-size: ${size}; line-height: ${s.lineHeight}; letter-spacing: ${s.letterSpacing}; font-weight: ${s.fontWeight}; }`;
  });
  return `/* GENERATED by scripts/gen-type-scale.mjs — do not hand-edit. */\n${lines.join("\n")}\n`;
}
